# Generate the l_ec self-convergence campaigns from the benchmark lattice_10x10_het3x:
# the FULL campaign (all 198 orbitals, neighbor_cutoff=5, same dielectric geometry), with ALL
# solver tolerances tied to 1e-5, at two edge-refinement levels giving l_ec = 2.27 Å (level 2)
# and l_ec = 1.14 Å (level 3). support_rtol is held at 1e-4 (a density-truncation, kept
# identical in both so the geometry is unchanged and only l_ec varies). The two runs produce full
# V_ijkl tensors to compare (on-site U diagonal + exchange symmetry) with scripts/compare_conv.jl.
#
# Run: julia --project=codes/article scripts/gen_benchmark_conv.jl
using TOML

const LS    = normpath(joinpath(@__DIR__, ".."))
# RERUN_BASE picks the campaign supplying templates/orbitals/dielectrics (so an eps=2.4 variant
# inherits that slab permittivity); RERUN_TAG suffixes the generated campaign names.
const BASE  = get(ENV, "RERUN_BASE", "lattice_10x10_het3x")
const TAG   = get(ENV, "RERUN_TAG", "")
const LEVELS = isempty(ARGS) ? [2, 3] : parse.(Int, ARGS)
const BENCH = joinpath(LS, "campaigns", BASE * ".toml")
const CEPH  = "/mnt/ceph/users/xgao1/four_index"
const TOL   = 1e-5            # tied solver tolerances
const SUPPORT_RTOL = 1e-4     # kept fixed (geometry-preserving)
const K_TARGET = parse(Int, get(ENV, "K_TARGET", "46"))   # pairs per batch; see write_toml

d = TOML.parsefile(BENCH)
orbs = d["orbital"]                                   # ALL 198 orbitals
boxes = d["dielectrics"]["boxes"]; eps_out = d["dielectrics"]["eps_out"]
templates = d["templates"]
cutoff = d["pairing"]["neighbor_cutoff"]              # 5.0 — full four-index pairing

function write_toml(name, level)
    io = IOBuffer()
    println(io, "# AUTO-GENERATED by scripts/gen_benchmark_conv.jl — l_ec self-convergence (FULL campaign).")
    println(io, "# All solver tolerances = $(TOL); edge_refine_level = $(level) (l_ec = 9/2^$(level)*1.01).")
    println(io, "name = \"$(name)\"")
    println(io, "root = \"$(CEPH)/$(name)\"")
    println(io, "templates = [")
    for t in templates; println(io, "  \"$(t)\","); end
    println(io, "]\n")
    for o in orbs
        println(io, "[[orbital]]"); println(io, "type = $(o["type"])")
        println(io, "x = $(o["x"])"); println(io, "y = $(o["y"])"); println(io, "z = $(o["z"])"); println(io)
    end
    println(io, "[pairing]")
    println(io, "neighbor_cutoff = $(cutoff)\n")
    println(io, "[dielectrics]")
    println(io, "eps_out = $(eps_out)")
    println(io, "boxes = [")
    for b in boxes; println(io, "  [", join(b, ", "), "],"); end
    println(io, "]\n")
    println(io, "[solve]")
    println(io, "n_quad = 6")
    println(io, "edge_refine_level = $(level)")
    println(io, "rhs_tol = $(TOL)")
    println(io, "lhs_tol = $(TOL)")
    println(io, "gmres_rtol = $(TOL)")
    println(io, "support_rtol = $(SUPPORT_RTOL)")
    println(io, "volume_tol = $(TOL)")
    # max_order 64, not 8. p_up is clamped to max_order with no adaptive fallback for
    # non-touching pairs and no warning; measured on a real conv_l3 interface (37,520
    # panels, up_tol 1e-5, n_quad 6), max_order = 8 left 92.5%% of the 12,208 upsample
    # pairs pinned at the cap, i.e. under-resolved. At 64 that falls to 55%%. The
    # remainder have rho_min < 1.094 -- nearly coincident but not edge-adjacent, so the
    # touching test routes them to upsampling where they would need p_up in the hundreds.
    println(io, "max_order = 64")
    println(io, "max_depth = 128\n")
    println(io, "[batching]")
    println(io, "n_centers_per_batch = 1")
    # Partition the pairs into spatially compact batches of ~k_target pairs (RCB on the pair
    # midpoints) instead of one batch per anchor: 2623 pairs become ~57 batches at K = 46 rather
    # than 198 at K = 1-17, so ~3.5x fewer interface builds / LHS operators / pottrg maps.
    # K = 46 is the cost floor of the Sec. 5.2 sequential single-node sweep: total time per pair
    # is 27.1 s at K = 31 and 25.2 s flat over K = 37-58, and 46 quantises best against 10 nodes
    # (6 rounds of 57 batches vs 9 rounds of 85 at K = 31). Peak RSS 634 GB = 42% of the node.
    # Do not raise it past 58: the K = 67-79 points decline ~8%, and 103 projects to 93% of RAM.
    println(io, "k_target = $(K_TARGET)\n")
    println(io, "[eval]")
    println(io, "c_pad = 5.0")
    write(joinpath(LS, "campaigns", "$(name).toml"), String(take!(io)))
end

for lv in LEVELS                      # level 2 -> l_ec = 2.27 A, level 3 -> l_ec = 1.14 A
    nm = "lattice_conv_l$(lv)$(TAG)"
    write_toml(nm, lv)
    println("wrote campaigns/$(nm).toml")
end
println("base=$(BASE)  orbitals=$(length(orbs))  neighbor_cutoff=$(cutoff)  all tol=$(TOL)  levels=$(LEVELS)")
