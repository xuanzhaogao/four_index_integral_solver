# Generate the redesigned four-index benchmark campaign `lattice_10x10_het3x`
# (spec: docs/superpowers/specs/2026-07-10-benchmark-het3x-and-geometry-viz-design.md):
#   - ×3 converged heterojunction substrate (270³ Si|SiO₂ cubes + graphene slab, ε = SLAB_EPS)
#   - ~200 orbitals: REAL hexagonal graphene lattice (both sublattices) clipped to a SQUARE
#     window centered on the junction (5.547, 10.318), z=7.5
#   - neighbor_cutoff = 5.0 → four-index V_ijkl for pairs within 5 Å
#
# Run: julia --project=codes/lattice_scale codes/lattice_scale/scripts/gen_benchmark_het3x.jl

# real hexagonal graphene lattice (same registry as lattice_10x10 / gen_onsite_campaign)
const A1 = (2.465, 0.0)
const A2 = (-1.2325, 2.1347526)
const SUBLATTICE = ((0.00093991, 0.00092506, 1), (-0.00013665, 1.42319335, 2))  # (x0, y0, type)
const ZORB = 7.5
const XJUNC = 5.547; const YCEN = 10.318          # junction = center of the square window
const HALF = 11.5                                  # square half-width (side ~23 Å) → ~200 orbitals

const L = 270.0                                   # ×3 cube edge (substrate stays big → converged)
const CZC = 3.0 - L / 2                            # cube center-z: top face at z=3
const SLAB_LZ = 9.0                                # slab thickness (unchanged; contains z-support)
const SLAB_EPS = 2.4                               # graphene effective ε from the cRPA article
const K_TARGET = parse(Int, get(ENV, "K_TARGET", "46"))   # pairs per batch; see build_toml
                                                   # (was 10.0, a generic system_fig1 demo value;
                                                   # the ε=10 run is preserved as lattice_10x10_het3x[_v2])
const MARGIN = 11.0                                # measured in-plane φ² support (~10) + buffer:
                                                   # slab Lx/Ly = block extent + 2·MARGIN so the
                                                   # orbital density is fully inside ε=10 (no leak)

site(Rx, Ry, sub) = (sub[1] + Rx * A1[1] + Ry * A2[1], sub[2] + Rx * A1[2] + Ry * A2[2])

# Real honeycomb (both sublattices) clipped to a square window centered on the junction.
function orbitals_honeycomb_square()
    orbs = Tuple{Int,Float64,Float64}[]           # (type, x, y)
    for Rx in -40:40, Ry in -40:40, sub in SUBLATTICE
        x, y = site(Rx, Ry, sub)
        (abs(x - XJUNC) <= HALF && abs(y - YCEN) <= HALF) && push!(orbs, (sub[3], x, y))
    end
    sort!(orbs, by = o -> (o[3], o[2]))           # row-major
    return orbs
end

const TEMPLATES = [
  "/mnt/ceph/users/mroesner/Graphene/cRPA4RSGW/graphene/monolayer/k_323201_nb_144_c_15/graphene_00001.xsf",
  "/mnt/ceph/users/mroesner/Graphene/cRPA4RSGW/graphene/monolayer/k_323201_nb_144_c_15/graphene_00002.xsf",
]

function build_toml(name, root, orbs)
    # slab lateral size = orbital-block extent + 2·MARGIN (tightly contains the φ² support)
    xr = extrema(o[2] for o in orbs); yr = extrema(o[3] for o in orbs)
    slab_lx = (xr[2] - xr[1]) + 2 * MARGIN
    slab_ly = (yr[2] - yr[1]) + 2 * MARGIN
    io = IOBuffer()
    println(io, "# AUTO-GENERATED by scripts/gen_benchmark_het3x.jl")
    println(io, "# 10×10 four-index benchmark: square super-lattice on the ×3 Si|SiO₂ heterojunction.")
    println(io, "name = \"$(name)\"")
    println(io, "root = \"$(root)\"")
    println(io, "templates = [")
    for t in TEMPLATES; println(io, "  \"$(t)\","); end
    println(io, "]\n")
    for (t, x, y) in orbs
        println(io, "[[orbital]]"); println(io, "type = $(t)")
        println(io, "x = $(x)"); println(io, "y = $(y)"); println(io, "z = $(ZORB)"); println(io)
    end
    println(io, "[pairing]")
    println(io, "neighbor_cutoff = 5.0\n")
    println(io, "[dielectrics]")
    println(io, "eps_out = 1.0")
    println(io, "boxes = [")
    println(io, "  [$(XJUNC - L/2), $(YCEN), $(CZC), $(L), $(L), $(L), 11.9],")   # Si (−x)
    println(io, "  [$(XJUNC + L/2), $(YCEN), $(CZC), $(L), $(L), $(L), 3.9],")    # SiO₂ (+x)
    println(io, "  [$(XJUNC), $(YCEN), 7.5, $(slab_lx), $(slab_ly), $(SLAB_LZ), $(SLAB_EPS)],")  # graphene slab (wraps orbital density)
    println(io, "]\n")
    # max_order 64, not 8: p_up is clamped to max_order with no adaptive fallback for
    # non-touching pairs and no warning. Measured on a real conv_l3 interface, max_order = 8
    # left 92.5% of upsample pairs pinned at the cap (under-resolved); 64 brings it to 55%.
    println(io, "[solve]")
    for (k, v) in ["n_quad"=>6, "edge_refine_level"=>2, "rhs_tol"=>1e-3, "lhs_tol"=>1e-5,
                   "gmres_rtol"=>1e-5, "support_rtol"=>1e-4, "volume_tol"=>1e-5,
                   "max_order"=>64, "max_depth"=>128]
        println(io, "$(k) = $(v)")
    end
    println(io, "\n[batching]")
    println(io, "n_centers_per_batch = 1")
    # Partition the pairs into spatially compact batches of ~k_target pairs (RCB on the pair
    # midpoints) instead of one batch per anchor: 2623 pairs become ~57 batches at K = 46 rather
    # than 198 at K = 1-17, so ~3.5x fewer interface builds / LHS operators / pottrg maps.
    # K = 46 is the cost floor of the Sec. 5.2 sequential single-node sweep: total time per pair
    # is 27.1 s at K = 31 and 25.2 s flat over K = 37-58, and 46 quantises best against 10 nodes
    # (6 rounds of 57 batches vs 9 rounds of 85 at K = 31). Peak RSS 634 GB = 42% of the node.
    # Do not raise it past 58: the K = 67-79 points decline ~8%, and 103 projects to 93% of RAM.
    println(io, "k_target = $(K_TARGET)\n")
    println(io, "[eval]")
    println(io, "c_pad = 5.0")
    return String(take!(io))
end

const OUTDIR = joinpath(@__DIR__, "..", "campaigns")
const CEPH = "/mnt/ceph/users/xgao1/four_index"

let orbs = orbitals_honeycomb_square(), nm = "lattice_10x10_het3x_eps2.4"
    write(joinpath(OUTDIR, "$(nm).toml"), build_toml(nm, "$(CEPH)/$(nm)", orbs))
    nsi = count(o -> o[2] < XJUNC, orbs)
    xr = extrema(o[2] for o in orbs); yr = extrema(o[3] for o in orbs)
    println("$(nm).toml: $(length(orbs)) orbitals (Si $(nsi) / SiO₂ $(length(orbs)-nsi)), " *
            "x∈[$(round(xr[1];digits=1)),$(round(xr[2];digits=1))] y∈[$(round(yr[1];digits=1)),$(round(yr[2];digits=1))]")
end
